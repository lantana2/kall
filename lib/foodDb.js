import BIG from './foodDbBig';

const STOP = new Set(['и', 'с', 'со', 'в', 'на', 'из', 'по', 'для', 'без', 'от']);
const LIMIT = 40; // максимум результатов

const norm = (s) => String(s).toLowerCase().replace(/ё/g, 'е');

function row2item([dish, calories, protein, fat, carbs]) {
  return { dish, grams: 100, calories, protein, fat, carbs, confidence: 'high', source: 'local' };
}

// Поиск по локальной базе: сначала курированные блюда (F), затем большая база OFF (BIG).
// Все значимые слова запроса должны входить в название.
export function searchLocal(query) {
  const tokens = norm(query).split(/\s+/).filter((t) => t.length >= 2 && !STOP.has(t));
  if (tokens.length === 0) return [];

  const match = (name) => {
    const n = norm(name);
    return tokens.every((t) => n.includes(t));
  };

  const res = [];
  const seen = new Set();
  const add = (row) => {
    const key = norm(row[0]);
    if (seen.has(key)) return;
    seen.add(key);
    res.push(row2item(row));
  };

  for (const row of F) if (res.length < LIMIT && match(row[0])) add(row);
  for (const row of BIG) {
    if (res.length >= LIMIT) break;
    if (match(row[0])) add(row);
  }
  return res;
}
