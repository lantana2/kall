const STOP = new Set(['и', 'с', 'со', 'в', 'на', 'из', 'по', 'для']);

// Поиск по локальной базе. Все значимые слова запроса должны входить в название.
export function searchLocal(query) {
  const tokens = String(query || '')
    .toLowerCase()
    .split(/\s+/)
    .filter((t) => t.length >= 2 && !STOP.has(t));
  if (tokens.length === 0) return [];

  return F.filter(([name]) => {
    const n = name.toLowerCase();
    return tokens.every((t) => n.includes(t));
  }).map(([dish, calories, protein, fat, carbs]) => ({
    dish,
    grams: 100,
    calories,
    protein,
    fat,
    carbs,
    confidence: 'high',
    source: 'local',
  }));
}
